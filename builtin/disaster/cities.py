def coord_of(province, city, district=""):
    """按 省/市/区县 取坐标；找不到返回 None。"""
    if province and city:
        prov = province if province in CITIES else _find_province(province)
        cname = _match_key(CITIES.get(prov, []), city) if prov else city
        if prov and cname and district:
            hit = _match(DISTRICTS.get((prov, cname), []), district)
            if hit:
                return hit
        if prov and cname:
            hit = _match(CITIES.get(prov, []), cname)
            if hit:
                return hit
    # 退化为按名字全局查找
    if city:
        hit = province_of_city(city)
        if hit[0]:
            return coord_of(hit[0], hit[1], "")
    return None


def _find_province(name):
    """按省名（可省后缀）匹配到 PROVINCES 里的全名。"""
    q = (name or "").strip()
    if not q:
        return ""
    for p in PROVINCES:
        if p == q or short_name(p) == short_name(q) or p.startswith(q):
            return p
    return ""


def _match_key(items, name):
    """在 [(名称, lat, lon)] 里找与 name 匹配的**条目名称**（用于二次查区县）。"""
    q = (name or "").strip()
    qs = short_name(q)
    for n, la, lo in items:
        if n == q or short_name(n) == qs:
            return n
    for n, la, lo in items:
        if n.startswith(qs) or qs.startswith(short_name(n)):
            return n
    return ""


def province_of_city(city):
    """按市/区县名反查 (省, 市)，找不到返回 ('', '')。"""
    q = (city or "").strip()
    if not q:
        return ("", "")
    hit = _INDEX.get(q) or _INDEX.get(short_name(q))
    return hit if hit else ("", "")
