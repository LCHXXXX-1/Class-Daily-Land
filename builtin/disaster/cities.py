def _match(items, name):
    """在 [(名称, lat, lon)] 里找 name：精确 -> 去后缀 -> 前缀。"""
    q = (name or "").strip()
    if not q:
        return None
    qs = short_name(q)
    for n, la, lo in items:
        if n == q:
            return (la, lo)
    for n, la, lo in items:
        if short_name(n) == qs:
            return (la, lo)
    for n, la, lo in items:
        sn = short_name(n)
        if n.startswith(qs) or qs.startswith(sn) or sn.startswith(qs):
            return (la, lo)
    return None


