def _parse(payload):
    cities, districts, provinces = {}, {}, []
    prov = None
    city = None
    for raw in payload.strip().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            prov = line[1:].strip()
            provinces.append(prov)
            cities.setdefault(prov, [])
            continue
        if prov is None:
            continue
        if line.startswith("~"):
            name, la, lo = line[1:].split("|")
            if city is not None:
                districts.setdefault((prov, city), []).append(
                    (name, float(la), float(lo)))
            continue
        name, la, lo = line.split("|")
        city = name
        cities[prov].append((name, float(la), float(lo)))
    return provinces, cities, districts


