def short_name(name):
    """去掉行政区后缀：成都市->成都、甘孜藏族自治州->甘孜藏族。"""
    n = (name or "").strip()
    for suf in _SUFFIX:
        if n.endswith(suf) and len(n) > len(suf):
            return n[: -len(suf)]
    return n

