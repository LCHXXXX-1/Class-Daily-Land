def haversine_km(lat1, lon1, lat2, lon2):
    """两点球面距离（km），保留 4 位小数（与参考实现一致）。"""
    p = math.pi / 180.0
    a = (math.sin((lat1 - lat2) * p / 2.0) ** 2
         + math.cos(lat1 * p) * math.cos(lat2 * p)
         * math.sin((lon1 - lon2) * p / 2.0) ** 2)
    a = min(1.0, max(0.0, a))
    return round(2 * math.asin(math.sqrt(a)) * EARTH_RADIUS_KM, 4)


def intensity_at(magnitude, distance_km):
    """本地烈度估算，负值取 0。"""
    try:
        v = (float(magnitude) * 1.363
             + 2.941
             - math.log(float(distance_km) + 7.0) * 1.494)
    except (TypeError, ValueError):
        return 0.0
    return 0.0 if v < 0 else v


def countdown_seconds(depth_km, distance_km):
    """横波到达倒计时（秒）。depth/distance 非法时返回 0。"""
    try:
        depth = float(depth_km if depth_km is not None else 0.0)
        dist = float(distance_km if distance_km is not None else 0.0)
    except (TypeError, ValueError):
        return 0.0
    if depth < 0 or dist < 0:
        return 0.0

    i = int(depth / 5.0)
    if i > 6:
        i = 6
    axis = ARRAY[0]
    row = ARRAY[i + 1]

    if dist > axis[-1]:
        return SLOPE[i] * dist + INTERCEPT[i]

    n = len(axis) - 1
    j = 0
    while j < n and dist >= axis[j]:
        j += 1
    i3 = j - 1
    i4 = i3 + 1
    return row[i3] + (row[i4] - row[i3]) * (
        (dist - axis[i3]) / (axis[i4] - axis[i3]))


def norm_thresholds(thresholds=None):
    """把用户配置的三个分界值规范化为递增的浮点元组，非法时回退默认。"""
    out = []
    for i, d in enumerate(DEFAULT_INTENSITY_THRESHOLDS):
        val = d
        try:
            val = float(thresholds[i])
        except (TypeError, ValueError, IndexError, KeyError):
            val = d
        if val < INTENSITY_MIN or val > INTENSITY_MAX:
            val = d
        out.append(val)
    out.sort()
    return tuple(out)


def level_of(intensity, thresholds=None):
    """预估烈度 -> 等级色键（分界可由 thresholds 自定义）。"""
    try:
        v = float(intensity)
    except (TypeError, ValueError):
        return "blue"
    t = norm_thresholds(thresholds)
    if v <= t[0]:
        return "blue"
    if v <= t[1]:
        return "yellow"
    if v <= t[2]:
        return "orange"
    return "red"


def intensity_ranges(thresholds=None):
    """各等级对应的烈度区间文字（设置页预览用）。

    返回 {'blue': '≤2.0', 'yellow': '2.1 - 3.0', ...}（保留一位小数）。
    """
    t = norm_thresholds(thresholds)
    return {
        "blue": "≤%.1f" % t[0],
        "yellow": "%.1f - %.1f" % (t[0] + 0.1, t[1]),
        "orange": "%.1f - %.1f" % (t[1] + 0.1, t[2]),
        "red": ">%.1f" % t[2],
    }


def level_color(level, colors=None):
    """等级色键 -> 颜色；colors 可覆盖（用户自定义配色）。"""
    if isinstance(colors, dict):
        c = colors.get(level)
        if isinstance(c, str) and c.strip():
            return c.strip()
    return LEVEL_COLORS.get(level, LEVEL_COLORS["blue"])


def level_name(level):
    return LEVEL_NAMES.get(level, "")


def level_word(level):
    """完整等级词：用于气象预警文案（'橙色预警'）。"""
    return LEVEL_WORDS.get(level, "")


def level_at_least(level, minimum):
    """level 是否 >= minimum（用于气象最低等级过滤）。"""
    return LEVEL_RANK.get(level, 0) >= LEVEL_RANK.get(minimum, 0)


def fmt_clock(ts):
    """epoch 秒 -> 北京时间 HH:MM:SS（固定 UTC+8，无夏令时）。"""
    try:
        t = time.gmtime(float(ts) + 8 * 3600)
    except (TypeError, ValueError):
        return "--:--:--"
    return "%02d:%02d:%02d" % (t.tm_hour, t.tm_min, t.tm_sec)


def fmt_clock_hm(ts):
    return fmt_clock(ts)[:5]


def evaluate(event, lat, lon, now=None, threshold=2.0,
             max_lead=DEFAULT_MAX_LEAD_SEC, max_age=DEFAULT_MAX_AGE_SEC,
             thresholds=None):
    """把一条地震事件换算为本地视角的派生数据（不落盘）。

    返回 dict 或 None（坐标/事件字段不可用时）：
      distance_km, local_intensity, level, countdown_sec, arrive_ts,
      remain_sec, phase('incoming'|'arrived'|'past'), triggered, displayable
    """
    if lat is None or lon is None:
        return None
    ev_lat = event.get("lat")
    ev_lon = event.get("lon")
    if ev_lat is None or ev_lon is None:
        return None

    now = time.time() if now is None else float(now)
    try:
        threshold = float(threshold)
    except (TypeError, ValueError):
        threshold = 2.0

    dist = haversine_km(float(lat), float(lon),
                        float(ev_lat), float(ev_lon))
    mag = float(event.get("magnitude") or 0.0)
    depth = float(event.get("depth") or 0.0)
    origin = float(event.get("origin_ts") or 0.0)

    inten = intensity_at(mag, dist)
    cd = countdown_seconds(depth, dist)
    arrive = origin + cd
    remain = arrive - now
    age = now - origin

    if remain > 0:
        phase = "incoming"
    elif now <= arrive + ARRIVED_HOLD_SEC:
        phase = "arrived"
    else:
        phase = "past"

    triggered = (inten > threshold
                 and phase == "incoming"
                 and remain <= max_lead
                 and age <= max_age
                 and origin <= now + 30)
    displayable = (inten > threshold
                   and phase in ("incoming", "arrived")
                   and age <= max_age + ARRIVED_HOLD_SEC)

    return {
        "kind": "quake",
        "uid": event.get("uid"),
        "distance_km": dist,
        "local_intensity": round(inten, 2),
        "level": level_of(inten, thresholds),
        "countdown_sec": cd,
        "arrive_ts": arrive,
        "remain_sec": remain,
        "phase": phase,
        "triggered": triggered,
        "displayable": displayable,
    }
